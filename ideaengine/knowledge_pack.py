def dead_ends(journal=None, min_tries: int = 5) -> str:
    """07: families that produced nothing (stop) and, since 1.7.0, the journal's leads (start here)."""
    lines = [_header("07_dead_ends.md", "Dead ends and leads from the journal"),
             f"A family is a dead end when it has at least {min_tries} live tries and none reached WEAK or better. "
             "New cards in these families need a genuinely different mechanism or data, not a variation.\n"]
    de = pd.DataFrame()
    if journal is not None:
        from hypolab import learning
        try:
            de = learning.dead_end_families(journal, min_tries)
        except Exception:  # noqa: BLE001
            de = pd.DataFrame()
    if not de.empty:
        lines += ["| Family | Regions | Tries | Best Sharpe |", "|---|---|---|---|"]
        lines += [f"| {r.family} | {r.regions} | {r.tries} | {r.best_sharpe} |" for r in de.itertuples(index=False)]
    else:
        lines.append("_None yet. This list fills in as the live journal grows._")
    # 1.10.3: what the Weekly Reviewer decided reaches the Writer and the Critic (before, only the journal kept it)
    dd = les = pd.DataFrame()
    if journal is not None:
        from hypolab import learning
        dd, les = learning.declared_dead_ends(journal), learning.recent_lessons(journal, 15)
    lines += ["", "## Dead ends declared by the Weekly Reviewer",
              "Families a weekly PLAN said to stop. Treat them like the measured dead ends above.", ""]
    lines += (["| Family | Declared |", "|---|---|"] + [f"| {r.family} | {r.week or r.date} |"
                                                      for r in dd.itertuples(index=False)]) if not dd.empty \
        else ["_None declared yet._"]
    lines += ["", "## Lessons (newest first)",
              "Rules written in the weekly reviews (and your own lessons from the Journal page). Follow them unless a "
              "card says why one does not apply.", ""]
    lines += [f"- {'[' + r.week + '] ' if r.week else ''}{r.text}" for r in les.itertuples(index=False)] \
        if not les.empty else ["_No lessons yet._"]
    lines += ["", "## Leads (1.7.0 learning loop)",
              "Evidence that something works but has no finished card yet. A good new card can start from one of "
              "these: write the mechanism for a scanned field, a sibling for a near miss that used its budget, or the "
              "reverse story for an inverted result. Never copy the expression without a mechanism.", ""]
    leads = []
    if journal is not None:
        from hypolab import learning
        try:
            for r in learning.scan_candidates(journal).head(10).itertuples(index=False):
                leads.append(f"| scan candidate | {r.region} {r.dataset}.{r.field} | Sharpe {r.sharpe} vs noise bar "
                             f"{r.noise_bar} ({r.n_probes} probes) |")
            for r in learning.near_misses(journal).head(10).itertuples(index=False):
                leads.append(f"| {'sibling wanted' if r.at_budget else 'near miss'} | {r.idea_id} | "
                             f"{r.best_verdict}, Sharpe {r.best_sharpe:.2f}, {int(r.tries_left)} tries left |")
            for r in learning.inverted(journal).head(10).itertuples(index=False):
                leads.append(f"| inverted | {r.idea_id} | Sharpe {r.sharpe:.2f} |")
        except Exception:  # noqa: BLE001
            leads = []
    if leads:
        lines += ["| Kind | Subject | Evidence |", "|---|---|---|"] + leads
    else:
        lines.append("_No leads yet._")
    return "\n".join(lines) + "\n"


def my_operator_usage(journal=None) -> str:
    lines = [_header("08_my_operator_usage.md", "Operators Zacc has and has not used this quarter")]
    try:
        from hypolab import account
        if journal is None or account.account_alphas(journal).empty:
            raise LookupError
        summary, by_cat, used, unused = account.operator_audit(journal)
    except Exception:  # noqa: BLE001
        lines.append("_Not available yet: download your submitted alphas on the Account page, then "
                     "regenerate this pack._")
        return "\n".join(lines) + "\n"
    lines += [f"Quarter {summary['quarter']}: {summary['regular counted']} regular alphas submitted, "
              f"{summary['distinct operators used']} of {summary['operators available']} operators used "
              f"(list from {summary['operator list from']}; {summary['left out of the count']} not counted).\n",
              "Rule for writers: choose operators for the mechanism. When two constructions test the idea equally "
              "well, prefer the one with an operator not used yet this quarter. Never add an operator only for "
              "coverage.\n", "| Category | Used / available | Not used yet |", "|---|---|---|"]
