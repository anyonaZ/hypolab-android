def published_predictors() -> str:
    """10 (1.9.0): Open Source Asset Pricing's published predictors - which ones a card already covers, and the rest
    as an idea bank (with the paper, so the Writer can cite it and the Critic can spot a renamed textbook factor)."""
    from ideaengine import collectors, sources
    lines = [_header("10_published_predictors.md", "Published cross-sectional predictors (Open Source Asset Pricing)"),
             f"Source: {collectors.OSAP_CITE} - their signal list (bundled with HYPOLAB, GPL-2.0). Each row is a "
             "predictor a paper found; t-stat and sign are from the original paper on US stocks. Published "
             "anomalies lose about a third of their power after publication (McLean & Pontiff 2016), so expect less "
             "on BRAIN and look for a new data angle. A card idea that restates one of these is a known anomaly: say "
             "which one, and what is new.\n"]
    try:
        items = collectors.read_osap()
    except Exception as e:  # noqa: BLE001
        return "\n".join(lines + [f"_Signal list not readable: {e}_"]) + "\n"
    lib = load_library()
    rows_cov, rows_new = [], []
    for it in items:
        ex = it.extra
        cov = sources.covered_by(it, lib)
        t = f"{ex['t_stat']:.1f}" if ex.get("t_stat") is not None else "-"
        sign = f"{ex['sign']:+d}" if isinstance(ex.get("sign"), int) else "?"
        row = (f"| {ex['acronym']} | {it.title} | {it.authors} ({it.year}) | {ex.get('osap_data')} -> "
               f"{CATEGORY_NAMES.get(ex.get('category'), ex.get('category'))} | {sign} | {t} | "
               f"{ex.get('predictability') or '-'} |")
        (rows_cov if cov else rows_new).append((row + f" {', '.join(cov)} |") if cov else row)
    lines += [f"## Not covered by any card yet ({len(rows_new)})",
              "| Signal | What | Paper | Data -> BRAIN category | Sign | t-stat | Predictability in the paper |",
              "|---|---|---|---|---|---|---|"] + rows_new
    lines += ["", f"## Same paper as an existing card ({len(rows_cov)})",
              "| Signal | What | Paper | Data -> BRAIN category | Sign | t-stat | Predictability in the paper | Card |",
              "|---|---|---|---|---|---|---|---|"] + rows_cov
    return "\n".join(lines) + "\n"


def build(out_dir: Path, journal=None, store=None) -> List[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "01_card_format.md": card_format(),
        "02_concepts.md": concepts(),
        "03_operators.md": operators(),
        "04_existing_cards.md": existing_cards(journal),
        "05_pyramids_guide.md": pyramids_guide(),
        "06_goals_and_rules.md": goals_and_rules(store, journal),
        "07_dead_ends.md": dead_ends(journal),
        "08_my_operator_usage.md": my_operator_usage(journal),
        "09_brain_rules.md": brain_rules(),
        "10_published_predictors.md": published_predictors(),
    }
    written, changed = PackResult(), []
    for name, text in files.items():
        p = out / name
        # 1.10.1: rewrite a file only when its content changed (the date line alone is not a change), so the file
        # dates - and the list below - tell you which ones to re-upload
        old = p.read_text() if p.exists() else None
        if old is None or _GEN.sub("", old) != _GEN.sub("", text):
            p.write_text(text)
            changed.append(name)
        written.append(p)
    stamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    index = ["# Knowledge pack - which file goes to which project", "",
             f"Last rebuilt {stamp}. Changed then (re-upload these): {', '.join(changed) or 'none'}.", "",
             "| File | Upload to |", "|---|---|"] + [f"| {n} | {', '.join(u)} |" for n, u in USED_BY.items()]
    index += ["", "Not generated (in claude_projects/, you keep them): re-upload when you change them, and "
              "HANDOFF_CONTRACTS.md after a HYPOLAB update.", "", "| File | Upload to |", "|---|---|"] + \
        [f"| {n} | {', '.join(u)} |" for n, u in STATIC_USED_BY.items()]
    (out / "INDEX.md").write_text("\n".join(index) + "\n")
    written.append(out / "INDEX.md")
    written.changed = changed
    return written


_GEN = re.compile(r"_Generated by HYPOLAB on \d{4}-\d{2}-\d{2}")


class PackResult(list):
    """The files of the pack; `.changed` names the ones whose content changed in this rebuild."""
    changed: List[str] = []


def main(argv: Optional[List[str]] = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    out = Path(argv[0]) if argv else Path("claude_projects") / "knowledge"
    journal = store = None
    try:
        from hypolab.journal import Journal
        from ideaengine.store import IdeaStore
        journal, store = Journal.open_readonly(), IdeaStore()
    except Exception as e:  # noqa: BLE001 - a pack without live data is still useful
        print(f"(no journal/goals read: {e})")
    res = build(out, journal, store)
    print(f"knowledge pack in {out}: {len(res)} files; changed (re-upload these): "
          f"{', '.join(res.changed) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
